#!/usr/bin/env bash
# Builds the release files into dist/
#
#   maxeco-V.tar.gz                 source (the folder maxeco-V/)
#   maxeco-V-1-x86_64.pkg.tar.zst   Arch and derivatives (pacman -U)
#   maxeco_V-1_amd64.deb            Debian, Ubuntu and derivatives (apt install ./)
#   maxeco-V-1.x86_64.rpm           Fedora, openSUSE and the rest (dnf / zypper)
#   install.sh                      the curl installer, same as in the repository
#   SHA256SUMS                      checked by install.sh before installing
#
#   packaging/build.sh              everything this machine can build
#   packaging/build.sh deb rpm      only these formats (arch, deb, rpm)
#
# All three packages come from the same build of the source tarball, done in a
# folder under /tmp, so no path of this machine ends up in them. Nothing here
# needs root. The .deb needs dpkg-deb, the .rpm needs rpmbuild, the Arch package
# only bsdtar (so it also builds outside Arch).
set -euo pipefail

TOP="$(cd "$(dirname "$0")/.." && pwd)"
VERSION=$(sed -n 's/^#define MAXECO_VERSION "\(.*\)"$/\1/p' "$TOP/src/maxeco.c")
REL=1
URL="https://github.com/gabrielmf1998/MaxEco"
PACKAGER="gabrielmf1998 <110578985+gabrielmf1998@users.noreply.github.com>"
SUMMARY="Tray slider with three power levels (Normal, Eco, MaxEco) for the CPU, GPUs and fans"
DIST="$TOP/dist"

msg() { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31mxx\033[0m %s\n' "$*" >&2; exit 1; }

[ -n "$VERSION" ] || die "no MAXECO_VERSION in src/maxeco.c"
grep -q "^pkgver=$VERSION\$" "$TOP/packaging/PKGBUILD" || die "PKGBUILD pkgver is not $VERSION"
grep -q "^Version: *$VERSION\$" "$TOP/packaging/maxeco.spec" || die "maxeco.spec Version is not $VERSION"

FORMATS=("$@")
[ ${#FORMATS[@]} -gt 0 ] || FORMATS=(arch deb rpm)
for f in "${FORMATS[@]}"; do
    case "$f" in arch|deb|rpm) ;; *) die "unknown format $f (arch, deb or rpm)" ;; esac
done

WORK=$(mktemp -d /tmp/maxeco-build.XXXXXX)
trap 'rm -rf "$WORK"' EXIT
# the same date on every file, so building the same commit twice gives the same tarball
if git -C "$TOP" rev-parse --git-dir >/dev/null 2>&1; then
    export SOURCE_DATE_EPOCH=$(git -C "$TOP" log -1 --format=%ct)
else
    export SOURCE_DATE_EPOCH=$(date +%s)
fi

# a full build starts from an empty dist/, a partial one only replaces its own files
if [ $# -eq 0 ]; then
    rm -rf "$DIST"
else
    for f in "${FORMATS[@]}"; do
        case "$f" in
            arch) rm -f "$DIST"/maxeco-*.pkg.tar.zst ;;
            deb)  rm -f "$DIST"/maxeco_*.deb ;;
            rpm)  rm -f "$DIST"/maxeco-*.rpm ;;
        esac
    done
    rm -f "$DIST"/maxeco-*.tar.gz "$DIST/SHA256SUMS"
fi
mkdir -p "$DIST"

# ------------------------------------------------------------------ source
SRCNAME="maxeco-$VERSION"
TARBALL="$DIST/$SRCNAME.tar.gz"
if git -C "$TOP" rev-parse --git-dir >/dev/null 2>&1; then
    if [ -n "$(git -C "$TOP" status --porcelain --untracked-files=no)" ] && [ "${ALLOW_DIRTY:-0}" != 1 ]; then
        die "uncommitted changes: commit them first (or ALLOW_DIRTY=1 for a test build of HEAD)"
    fi
    git -C "$TOP" archive --format=tar.gz --prefix="$SRCNAME/" -o "$TARBALL" HEAD
else
    # no git yet: the files a checkout would have
    tar -C "$TOP" --sort=name --mtime="@$SOURCE_DATE_EPOCH" --owner=0 --group=0 --numeric-owner \
        --exclude=build --exclude=dist --exclude=packaging/pkg --exclude=packaging/src \
        --exclude='*.pkg.tar.*' --exclude=__pycache__ \
        --transform="s,^\.,$SRCNAME," -czf "$TARBALL" .
fi
msg "source  $(basename "$TARBALL")"

tar -C "$WORK" -xzf "$TARBALL"
SRC="$WORK/$SRCNAME"
make -s -C "$SRC"
"$SRC/tests/t_helper.sh" "$SRC/build/maxeco-helper" > "$WORK/t_helper.log" \
    || { cat "$WORK/t_helper.log"; die "helper tests failed"; }
STAGE="$WORK/stage"
make -s -C "$SRC" DESTDIR="$STAGE" PREFIX=/usr install
strip --strip-all "$STAGE/usr/lib/maxeco/maxeco-helper"
# the helper is the only part linked to the C library: the newest symbol it uses
GLIBC_MIN=$(objdump -T "$STAGE/usr/lib/maxeco/maxeco-helper" | grep -oE 'GLIBC_[0-9]+\.[0-9]+' \
            | sed 's/GLIBC_//' | sort -V | tail -1)
[ "$GLIBC_MIN" = 2.34 ] || die "the helper now needs glibc $GLIBC_MIN, update the Depends lines and the README"

# ------------------------------------------------------------------ pacman
build_arch() {
    command -v bsdtar >/dev/null || die "bsdtar not found (libarchive)"
    local root="$WORK/arch" out="$DIST/maxeco-$VERSION-$REL-x86_64.pkg.tar.zst"
    cp -a "$STAGE" "$root"
    install -m644 "$SRC/packaging/maxeco.install" "$root/.INSTALL"
    local size; size=$(du -sb --exclude=.INSTALL "$root" | cut -f1)
    cat > "$root/.PKGINFO" <<INFO
# Generated by packaging/build.sh
pkgname = maxeco
pkgbase = maxeco
xdata = pkgtype=pkg
pkgver = $VERSION-$REL
pkgdesc = $SUMMARY
url = $URL
builddate = $SOURCE_DATE_EPOCH
packager = $PACKAGER
size = $size
arch = x86_64
license = MIT
depend = glibc
depend = systemd
depend = polkit
optdepend = nvidia-utils: limits for NVIDIA graphics cards
optdepend = libkscreen: optional 60 Hz screens in MaxEco on KDE Plasma (kscreen-doctor)
makedepend = gcc
makedepend = make
INFO
    # .MTREE is the file index pacman checks on install, owned by root like any Arch package
    ( cd "$root" && LANG=C bsdtar -czf .MTREE --format=mtree --uid 0 --gid 0 --uname root --gname root \
        --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' .PKGINFO .INSTALL usr )
    # .PKGINFO has to be the first member
    ( cd "$root" && LANG=C bsdtar --zstd -cf "$out" --uid 0 --gid 0 --uname root --gname root \
        .PKGINFO .MTREE .INSTALL usr )
    msg "arch    $(basename "$out")"
}

# ------------------------------------------------------------------ deb
build_deb() {
    command -v dpkg-deb >/dev/null || die "dpkg-deb not found"
    local root="$WORK/deb" out="$DIST/maxeco_${VERSION}-${REL}_amd64.deb"
    cp -a "$STAGE" "$root"
    # Debian keeps the license as the package's copyright file
    install -Dm644 "$SRC/LICENSE" "$root/usr/share/doc/maxeco/copyright"
    rm -rf "$root/usr/share/licenses"
    install -m644 "$SRC/README.md" "$SRC/README.pt-BR.md" "$root/usr/share/doc/maxeco/"
    local size; size=$(du -ks "$root" | cut -f1)
    mkdir -p "$root/DEBIAN"
    cat > "$root/DEBIAN/control" <<CONTROL
Package: maxeco
Version: $VERSION-$REL
Section: utils
Priority: optional
Architecture: amd64
Depends: libc6 (>= $GLIBC_MIN), systemd, polkitd | policykit-1
Maintainer: $PACKAGER
Installed-Size: $size
Homepage: $URL
Description: $SUMMARY
 A three step slider in the system tray. Normal runs everything as usual,
 Eco cuts the power of the CPU and the graphics cards while games stay
 playable, and MaxEco puts them at the lowest power the hardware allows.
 Going back to Normal puts everything back exactly as it was.
 .
 The tray program is freestanding C (about 64 KB of memory, no CPU while
 idle). A small root helper, started through systemd and allowed by a
 polkit rule, changes the CPU frequency limits, the AMD and NVIDIA (through
 NVML) graphics card limits and the Nuvoton motherboard fan curves.
CONTROL
    cat > "$root/DEBIAN/postinst" <<'POST'
#!/bin/sh
set -e
if [ -d /run/systemd/system ]; then
    systemctl daemon-reload >/dev/null 2>&1 || true
fi
POST
    cat > "$root/DEBIAN/prerm" <<'PRERM'
#!/bin/sh
set -e
# removal (not an upgrade): back to Normal while the helper still exists
if [ "$1" = remove ] && [ -d /run/systemd/system ]; then
    systemctl stop maxeco.service >/dev/null 2>&1 || true
fi
PRERM
    cat > "$root/DEBIAN/postrm" <<'POSTRM'
#!/bin/sh
set -e
if [ -d /run/systemd/system ]; then
    systemctl daemon-reload >/dev/null 2>&1 || true
fi
POSTRM
    chmod 0755 "$root/DEBIAN/postinst" "$root/DEBIAN/prerm" "$root/DEBIAN/postrm"
    ( cd "$root" && find usr -type f -print0 | sort -z | xargs -0 md5sum > DEBIAN/md5sums )
    dpkg-deb --root-owner-group -Zxz --build "$root" "$out" >/dev/null
    msg "deb     $(basename "$out")"
}

# ------------------------------------------------------------------ rpm
build_rpm() {
    command -v rpmbuild >/dev/null || die "rpmbuild not found"
    local topdir="$WORK/rpm"
    mkdir -p "$topdir/SOURCES" "$topdir/SPECS"
    cp "$TARBALL" "$topdir/SOURCES/"
    cp "$SRC/packaging/maxeco.spec" "$topdir/SPECS/"
    # --nodeps: BuildRequires are looked up in the rpm database, empty outside rpm distros
    # _rpmformat 4 and xz: rpm 6 makes v6 packages with zstd by default, which
    # older rpm versions (still on LTS distros) may not read
    rpmbuild --quiet --nodeps --define "_topdir $topdir" --define "_buildhost maxeco-build" \
        --define "_rpmformat 4" --define "_binary_payload w9.xzdio" \
        --define "use_source_date_epoch_as_buildtime 1" --define "clamp_mtime_to_source_date_epoch 1" \
        -bb "$topdir/SPECS/maxeco.spec" > "$WORK/rpmbuild.log" 2>&1 \
        || { cat "$WORK/rpmbuild.log"; die "rpmbuild failed"; }
    local out
    out=$(find "$topdir/RPMS" -name "maxeco-$VERSION-$REL.x86_64.rpm")
    [ -n "$out" ] || die "rpmbuild did not make maxeco-$VERSION-$REL.x86_64.rpm"
    cp "$out" "$DIST/"
    msg "rpm     $(basename "$out")"
}

for f in "${FORMATS[@]}"; do "build_$f"; done

install -m755 "$TOP/install.sh" "$DIST/install.sh"
( cd "$DIST" && sha256sum -- * > "$WORK/SHA256SUMS" && mv "$WORK/SHA256SUMS" SHA256SUMS )
msg "sums    SHA256SUMS"
